// Capturas para el README (interfaz en inglés). Uso: node readme_shots.js URL salida/
const { chromium } = require('/opt/node22/lib/node_modules/playwright');
const fs = require('fs'), path = require('path');
const url = process.argv[2], out = process.argv[3];
const mark = n => fs.writeFileSync(path.join(out, 'm_' + n), '');
const sleep = ms => new Promise(r => setTimeout(r, ms));
(async () => {
  const b = await chromium.launch();
  const ctx = await b.newContext({ viewport: { width: 390, height: 780 }, deviceScaleFactor: 2, isMobile: true, hasTouch: true, locale: 'en-US', colorScheme: 'dark',
    userAgent: 'Mozilla/5.0 (iPhone; CPU iPhone OS 17_0 like Mac OS X) AppleWebKit/605.1.15 (KHTML, like Gecko) Version/17.0 Mobile/15E148 Safari/604.1' });
  const p = await ctx.newPage();
  const shot = async n => { await sleep(400); await p.screenshot({ path: path.join(out, n + '.png') }); };
  await p.goto(url.split('#')[0]);
  await p.waitForSelector('#pin input');
  await shot('r_web_pin');
  await p.goto('about:blank');
  await p.goto(url);
  await p.waitForSelector('#list .row');
  await shot('r_web_home');
  mark('root');
  await p.click('.chip:has-text("Screenshots")');
  await p.waitForSelector('.row');
  await p.click('#bview');
  await p.waitForSelector('.tile img');
  await sleep(1500);
  await shot('r_web_grid');
  await p.click('.tile >> nth=0');
  await p.waitForSelector('.viewer img');
  await sleep(700);
  await shot('r_web_viewer');
  await p.click('[data-v="x"]');
  await p.click('#bview');
  await p.click('.chip:has-text("CIAs")');
  await p.waitForSelector('.row');
  const cdp = await ctx.newCDPSession(p);
  await cdp.send('Network.emulateNetworkConditions', { offline: false, latency: 5, downloadThroughput: -1, uploadThroughput: 700 * 1024 });
  const f1 = path.join(out, 'Pokemon Ultra Sun.cia'), f2 = path.join(out, 'Theme - Starry Night.cia');
  fs.writeFileSync(f1, Buffer.alloc(14 * 1024 * 1024, 1)); fs.writeFileSync(f2, Buffer.alloc(3 * 1024 * 1024, 2));
  await p.setInputFiles('#fpick', [f1, f2]);
  await sleep(4500);
  mark('up');
  await shot('r_web_upload');
  await p.waitForSelector('.qh:has-text("finished")', { timeout: 120000 });
  await cdp.send('Network.emulateNetworkConditions', { offline: false, latency: 0, downloadThroughput: -1, uploadThroughput: -1 });
  await p.click('[data-qclose]');
  await sleep(800);
  await shot('r_web_cias');
  const pc = await b.newContext({ viewport: { width: 1280, height: 760 }, locale: 'en-US', colorScheme: 'dark' });
  const p2 = await pc.newPage();
  await p2.goto(url);
  await p2.waitForSelector('#list .row');
  await p2.click('.chip:has-text("Screenshots")');
  await p2.click('#bview');
  await p2.waitForSelector('.tile img');
  await sleep(1500);
  await p2.screenshot({ path: path.join(out, 'r_web_pc.png') });
  mark('done');
  await b.close();
})().catch(e => { console.log('EXCEPCIÓN', e.message); mark('done'); });
